const catalogs: Record<Locale, Record<MessageKey, string>> = { en, 'zh-TW': zhTW }

export function translate(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}) {
  return Object.entries(params).reduce((message, [name, value]) => message.replaceAll(`{${name}}`, String(value)), catalogs[locale][key])
}

const templateKeys: Record<TemplateType, MessageKey> = {
  endurance: 'template.endurance', hills: 'template.hills', speed: 'template.speed',
}
const effortKeys: Record<Intensity, MessageKey> = { easy: 'effort.easy', strong: 'effort.strong', max: 'effort.max', recovery: 'effort.recovery' }
const helpKeys: Record<Intensity, MessageKey> = { easy: 'effort.easyHelp', strong: 'effort.strongHelp', max: 'effort.maxHelp', recovery: 'effort.recoveryHelp' }
const cueKeys: Record<Intensity, MessageKey> = { easy: 'cue.easy', strong: 'cue.strong', max: 'cue.max', recovery: 'cue.recovery' }

export function templateLabel(locale: Locale, type: TemplateType) { return translate(locale, templateKeys[type]) }
export function effortLabel(locale: Locale, effort: Intensity) { return translate(locale, effortKeys[effort]) }
export function effortHelp(locale: Locale, effort: Intensity) { return translate(locale, helpKeys[effort]) }

export function phaseLabel(locale: Locale, block: Pick<WorkoutBlock, 'kind' | 'mainBlockIndex'>, mainCount: number) {
  if (block.kind === 'main') return translate(locale, 'phase.block', { current: block.mainBlockIndex ?? 1, total: mainCount })
  return translate(locale, `phase.${block.kind}` as 'phase.warmup' | 'phase.recovery' | 'phase.cooldown')
}

export function intervalCue(locale: Locale, interval: Pick<WorkoutInterval, 'bookend' | 'intensity'>) {
  if (interval.bookend === 'warmup') return translate(locale, 'cue.warmup')
  if (interval.bookend === 'cooldown') return translate(locale, 'cue.cooldown')
  return translate(locale, cueKeys[interval.intensity])
}
